/* Annotation file: a line "exposure: ..." (B buried, E exposed) and/or a
   line "structure: ..." (E extended, H helix, O other; the other DSSP
   states G I B S T C count as other), one character per alignment site,
   with '?', 'X' or '-' for unknown. Blank characters are ignored; lines
   starting with '#' are comments. Returns the class of each site (-1 if
   unknown). */

static int STRUCT_Exposure_Code(char c)
{
  switch (toupper((unsigned char)c))
  {
  case 'B': return 0;
  case 'E': return 1;
  case '?': case 'X': case '-': return -1;
  }
  return -2;
}

static int STRUCT_Structure_Code(char c)
{
  switch (toupper((unsigned char)c))
  {
  case 'E': return 0;
  case 'H': return 1;
  case 'O': case 'G': case 'I': case 'B': case 'S': case 'T': case 'C':
    return 2;
  case '?': case 'X': case '-': return -1;
  }
  return -2;
}

short *STRUCT_Read_File(const char *file, int partition, int n_site)
{
  FILE  *fp;
  char  *line, *p, *key;
  short *expo, *sstr, *cls;
  int    n_expo, n_sstr, i, code, is_expo;

  fp = fopen(file, "r");
  if (fp == NULL)
  {
    PhyML_Fprintf(stderr, "\n. Cannot open the structure annotation file '%s'.\n",
                  file);
    Exit("\n");
  }

  line   = (char *)mCalloc(T_MAX_LINE, sizeof(char));
  expo   = (short *)mCalloc(n_site, sizeof(short));
  sstr   = (short *)mCalloc(n_site, sizeof(short));
  n_expo = n_sstr = -1;

  while (fgets(line, T_MAX_LINE, fp))
  {
    for (p = line; isspace((unsigned char)*p); p++)
      ;
    if (*p == '\0' || *p == '#') continue;
    key = p;
    p   = strchr(key, ':');
    if (p == NULL)
    {
      PhyML_Fprintf(stderr, "\n. Structure annotation file '%s': expected lines "
                            "'exposure: ...' and/or 'structure: ...'.\n",
                    file);
      Exit("\n");
    }
    *p++ = '\0';
    for (i = 0; key[i]; i++) key[i] = (char)tolower((unsigned char)key[i]);
    while (i > 0 && isspace((unsigned char)key[i - 1])) key[--i] = '\0';
    if (!strcmp(key, "exposure"))
      is_expo = YES;
    else if (!strcmp(key, "structure"))
      is_expo = NO;
    else
    {
      PhyML_Fprintf(stderr, "\n. Structure annotation file '%s': unknown line "
                            "'%s' (use 'exposure' or 'structure').\n",
                    file, key);
      Exit("\n");
    }

    i = 0;
    for (; *p; p++)
    {
      if (isspace((unsigned char)*p)) continue;
      code = is_expo ? STRUCT_Exposure_Code(*p) : STRUCT_Structure_Code(*p);
      if (code == -2)
      {
        PhyML_Fprintf(stderr, "\n. Structure annotation file '%s': invalid "
                              "%s character '%c'.\n",
                      file, is_expo ? "exposure" : "structure", *p);
        Exit("\n");
      }
      if (i < n_site) (is_expo ? expo : sstr)[i] = (short)code;
      i++;
    }
    if (i != n_site)
    {
      PhyML_Fprintf(stderr, "\n. Structure annotation file '%s': the %s line "
                            "has %d characters, the alignment %d sites.\n",
                    file, is_expo ? "exposure" : "structure", i, n_site);
      Exit("\n");
    }
    if (is_expo) n_expo = i; else n_sstr = i;
  }
  fclose(fp);
  Free(line);

  if ((partition == STRUCT_EX || partition == STRUCT_EX_EHO) && n_expo < 0)
  {
    PhyML_Fprintf(stderr, "\n. Structure annotation file '%s': this model needs "
                          "an 'exposure:' line.\n", file);
    Exit("\n");
  }
  if ((partition == STRUCT_EHO || partition == STRUCT_EX_EHO) && n_sstr < 0)
  {
    PhyML_Fprintf(stderr, "\n. Structure annotation file '%s': this model needs "
                          "a 'structure:' line.\n", file);
    Exit("\n");
  }

  cls = (short *)mCalloc(n_site, sizeof(short));
  for (i = 0; i < n_site; i++)
  {
    if (partition == STRUCT_EX)
      cls[i] = expo[i];
    else if (partition == STRUCT_EHO)
      cls[i] = sstr[i];
    else
      cls[i] = (expo[i] < 0 || sstr[i] < 0) ? -1 : (short)(expo[i] * 3 + sstr[i]);
  }
  Free(expo);
  Free(sstr);
  return cls;
}

