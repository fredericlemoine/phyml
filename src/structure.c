/* Matrices, global rates and class proportions of each partition. The
   proportions are those of the authors' PhyML-Structure binary
   (phyml-mixSS, ATGC Montpellier). EX and EHO rates: those of the binary
   (0.672021 and 1.641347; 0.720274, 0.976799 and 0.783109) divided by their
   mean under these proportions, so that the mean rate is 1, as for LG; the
   authors' mix_RatesProps.txt gives the same values to 4 decimals. EX_EHO:
   rates of Le & Gascuel (2010) as in the binary (in the paper: buried &
   other 0.535, exposed & helix 2.064; values from IQ-TREE's EX_EHO). */

static const int struct_first_matrix[4] = {0, 0, 2, 5};
static const int struct_n_class[4]      = {0, 2, 3, 6};
static const phydbl struct_rates[STRUCT_N_MATRICES] = {
    0.556729, 1.359756,                /* EX: buried, exposed */
    0.857583, 1.163010, 0.932396,      /* EHO: extended, helix, other */
    0.761816796788931, 0.744425646802117, 0.532457759429489,
    1.5639387472863,   2.06403411829438,  1.43336795177594}; /* EX_EHO */
static const phydbl struct_props[STRUCT_N_MATRICES] = {
    0.448, 0.552,                       /* EX */
    0.207793, 0.360558, 0.431649,       /* EHO */
    0.132640, 0.170755, 0.144605, 0.075153, 0.189803, 0.287044}; /* EX_EHO */
static const char *struct_class_names[STRUCT_N_MATRICES] = {
    "buried", "exposed", "extended", "helix", "other",
    "buried & extended", "buried & helix", "buried & other",
    "exposed & extended", "exposed & helix", "exposed & other"};

