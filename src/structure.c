/* Weight of a component for a site, without the Gamma probability. */

static phydbl STRUCT_Comp_Weight(const t_struct *s, int site, int k)
{
  int cls = (s->site_class != NULL) ? s->site_class[site] : -1;

  switch (s->model)
  {
  case STRUCT_MIX: return s->props[k];
  case STRUCT_PART:
    if (cls < 0) return s->props[k];
    return (k == cls) ? 1.0 : 0.0;
  case STRUCT_CONF_LG:
    if (cls < 0) return (k == s->n_class) ? 1.0 : 0.0;
    if (k == cls) return s->chi;
    return (k == s->n_class) ? 1.0 - s->chi : 0.0;
  case STRUCT_CONF_MIX:
    if (cls < 0) return s->props[k];
    return ((k == cls) ? s->chi : 0.0) + (1.0 - s->chi) * s->props[k];
  }
  assert(FALSE);
  return 0.0;
}

//////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////

/* Weight of rate category catg in the likelihood of a site pattern. */

phydbl STRUCT_Weight(const t_struct *s, int site, int catg)
{
  int k = catg / s->n_gamma;
  return STRUCT_Comp_Weight(s, site, k) * s->gamma_p[catg % s->n_gamma];
}

