//////////////////////////////////////////////////////////////

/* Rates of the n_comp x n_gamma categories: Gamma rate times the
   component's global rate. Called by Update_RAS. */

void STRUCT_Update_RAS(t_mod *mod)
{
  t_struct *s = mod->smod;
  int       k, g;

  DiscreteGamma(s->gamma_p, s->gamma_rr, mod->ras->alpha->v,
                mod->ras->alpha->v, s->n_gamma, mod->ras->gamma_median);
  if (s->n_gamma == 1)
  {
    s->gamma_rr[0] = 1.0;
    s->gamma_p[0]  = 1.0;
  }

  for (k = 0; k < s->n_comp; k++)
    for (g = 0; g < s->n_gamma; g++)
    {
      mod->ras->gamma_rr->v[k * s->n_gamma + g] = s->gamma_rr[g] * s->rate[k];
      mod->ras->gamma_r_proba->v[k * s->n_gamma + g] =
          s->gamma_p[g] / s->n_comp;
    }

  STRUCT_Update_Props(s);
}

