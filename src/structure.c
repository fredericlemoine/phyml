void STRUCT_Free(t_struct *s)
{
  int k;

  if (s == NULL) return;
  for (k = 0; k < s->n_comp; k++) Free_Eigen(s->eig[k]);
  Free(s->gamma_rr);
  Free(s->gamma_p);
  if (s->site_class) Free(s->site_class);
  if (s->class_count) Free(s->class_count);
  Free(s);
}

