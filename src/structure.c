/* Transition matrix of category catg for a length l already multiplied by
   the category's rate. */

void STRUCT_PMat(phydbl l, const t_struct *s, int catg, int ns, int pos,
                 phydbl *Pij, phydbl *tPij)
{
  int k = catg / s->n_gamma;
  if (k >= s->n_comp) k = s->n_comp - 1;
  PMat_Eigen(l, s->eig[k], ns, pos, Pij, tPij);
}

