/* Copy with its own parameters (chi, proportions) and data, e.g. for
   bootstrap replicates, which must not change the main model. */

t_struct *STRUCT_Copy(const t_struct *s)
{
  t_struct *c;
  int       k;

  c = STRUCT_Make(s->partition, s->model, s->n_gamma);
  c->chi       = s->chi;
  c->opt_chi   = s->opt_chi;
  c->opt_props = s->opt_props;
  for (k = 0; k < s->n_class; k++)
  {
    c->props[k]     = s->props[k];
    c->props_log[k] = s->props_log[k];
  }
  c->n_pattern = s->n_pattern;
  if (s->site_class)
  {
    c->site_class = (short *)mCalloc(s->n_pattern, sizeof(short));
    for (k = 0; k < s->n_pattern; k++) c->site_class[k] = s->site_class[k];
  }
  if (s->class_count)
  {
    c->class_count = (int *)mCalloc(s->n_class, sizeof(int));
    for (k = 0; k < s->n_class; k++) c->class_count[k] = s->class_count[k];
  }
  return c;
}

