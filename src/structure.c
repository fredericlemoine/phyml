/* Estimate chi and the class proportions (Brent, one at a time). */

void STRUCT_Optimize(t_tree *tree, int verbose)
{
  t_struct *s = tree->mod->smod;
  int       k;

  if (s == NULL) return;

  if (s->opt_chi == YES)
  {
    Generic_Brent_Lk(&s->chi, 0.0, 1.0, tree->mod->s_opt->min_diff_lk_local,
                     tree->mod->s_opt->brent_it_max,
                     tree->mod->s_opt->quickdirty, Wrap_Lk, NULL, tree, NULL,
                     NO, NO);
    if (verbose) Print_Lk(tree, "[Struct. chi       ]");
  }

  if (s->opt_props == YES)
  {
    // props_log[0] stays 0: the others are relative to it
    for (k = 1; k < s->n_class; k++)
      Generic_Brent_Lk(&s->props_log[k], -20.0, 20.0,
                       tree->mod->s_opt->min_diff_lk_local,
                       tree->mod->s_opt->brent_it_max,
                       tree->mod->s_opt->quickdirty, Wrap_Lk, NULL, tree, NULL,
                       NO, NO);
    STRUCT_Update_Props(s);
    if (verbose) Print_Lk(tree, "[Struct. props     ]");
  }

  Lk(NULL, tree);
}

