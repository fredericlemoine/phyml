const char *STRUCT_Model_Name(int partition, int model)
{
  static char name[64];
  const char *p = (partition == STRUCT_EX)    ? "EX"
                  : (partition == STRUCT_EHO) ? "EHO"
                                              : "EX_EHO";
  const char *m = (model == STRUCT_MIX)       ? "MIX"
                  : (model == STRUCT_PART)    ? "PART"
                  : (model == STRUCT_CONF_LG) ? "CONF/LG"
                                              : "CONF/MIX";
  snprintf(name, sizeof(name), "%s_%s", p, m);
  return name;
}

const char *STRUCT_Class_Name(int partition, int class_num)
{
  return struct_class_names[struct_first_matrix[partition] + class_num];
}

