t_struct *STRUCT_Make(int partition, int model, int n_gamma)
{
  t_struct *s;
  phydbl    daa[400], f[20], sum;
  int       k, m, i;

  assert(partition >= STRUCT_EX && partition <= STRUCT_EX_EHO);
  assert(n_gamma >= 1);

  s            = (t_struct *)mCalloc(1, sizeof(t_struct));
  s->partition = partition;
  s->model     = model;
  s->n_class   = struct_n_class[partition];
  s->n_comp    = s->n_class + (model == STRUCT_CONF_LG ? 1 : 0);
  s->n_gamma   = n_gamma;
  s->gamma_rr  = (phydbl *)mCalloc(n_gamma, sizeof(phydbl));
  s->gamma_p   = (phydbl *)mCalloc(n_gamma, sizeof(phydbl));

  for (k = 0; k < s->n_comp; k++)
  {
    for (i = 0; i < 400; i++) daa[i] = 0.0;
    if (k < s->n_class)
    {
      m = struct_first_matrix[partition] + k;
      Init_Qmat_Lower_Triangle(daa, f, struct_matrices[m],
                               struct_matrices[m] + 190);
      s->rate[k] = struct_rates[m];
    }
    else // CONF/LG: LG for sites with unreliable annotations
    {
      Init_Qmat_LG(daa, f);
      s->rate[k] = 1.0;
    }
    sum = 0.0;
    for (i = 0; i < 20; i++) sum += f[i];
    for (i = 0; i < 20; i++) s->pi[k][i] = f[i] / sum;
    s->eig[k] = Make_Normalised_Eigen(daa, s->pi[k], 20);
  }

  // Starting values, as in the authors' binary
  s->chi       = 0.8;
  s->opt_chi   = (model == STRUCT_CONF_LG || model == STRUCT_CONF_MIX) ? YES : NO;
  s->opt_props = (model == STRUCT_MIX || model == STRUCT_CONF_MIX) ? YES : NO;
  STRUCT_Set_Props(s, struct_props + struct_first_matrix[partition]);

  return s;
}

