//////////////////////////////////////////////////////////////

/* Class proportions, stored through their logs. */

void STRUCT_Set_Props(t_struct *s, const phydbl *props)
{
  int k;

  for (k = 0; k < s->n_class; k++)
    s->props_log[k] = (props[k] > 0.0) ? log(props[k]) : -30.0;
  STRUCT_Update_Props(s);
}

//////////////////////////////////////////////////////////////
//////////////////////////////////////////////////////////////

void STRUCT_Update_Props(t_struct *s)
{
  phydbl max, sum;
  int    k;

  max = s->props_log[0];
  for (k = 1; k < s->n_class; k++) max = MAX(max, s->props_log[k]);
  sum = 0.0;
  for (k = 0; k < s->n_class; k++) sum += exp(s->props_log[k] - max);
  for (k = 0; k < s->n_class; k++)
    s->props[k] = exp(s->props_log[k] - max) / sum;
}

