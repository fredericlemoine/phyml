const phydbl *STRUCT_Pi(const t_struct *s, int catg)
{
  int k = catg / s->n_gamma;
  if (k >= s->n_comp) k = s->n_comp - 1;
  return s->pi[k];
}

eigen *STRUCT_Eigen(const t_struct *s, int catg)
{
  int k = catg / s->n_gamma;
  if (k >= s->n_comp) k = s->n_comp - 1;
  return s->eig[k];
}

