void STRUCT_Print(FILE *fp, const t_tree *tree)
{
  const t_struct *s = tree->mod->smod;
  int             k, n;

  PhyML_Fprintf(fp, "\n. Structure model (Le & Gascuel 2010): \t%s",
                STRUCT_Model_Name(s->partition, s->model));
  if (s->model == STRUCT_CONF_LG || s->model == STRUCT_CONF_MIX)
    PhyML_Fprintf(fp, "\n  - Confidence coefficient chi: \t%.4f", s->chi);
  for (k = 0; k < s->n_class; k++)
  {
    PhyML_Fprintf(fp, "\n  - Class %-20s rate %.4f", STRUCT_Class_Name(s->partition, k),
                  s->rate[k]);
    if (s->model != STRUCT_PART) PhyML_Fprintf(fp, ", proportion %.4f", s->props[k]);
    if (s->class_count)
      PhyML_Fprintf(fp, ", annotated sites %d", s->class_count[k]);
  }
  if (s->site_class)
  {
    n = 0;
    for (k = 0; k < s->n_pattern; k++)
      if (s->site_class[k] < 0) n++;
    PhyML_Fprintf(fp, "\n  - Sites without annotation: \t%d", n);
  }
  PhyML_Fprintf(fp, "\n  - Branch lengths multiplied by: \t%.4f (mean rate)",
                STRUCT_Mean_Rate(tree));
}
