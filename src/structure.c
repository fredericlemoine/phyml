/* Expected substitution rate per site under the model: branch lengths are
   multiplied by it in the output (Le & Gascuel 2010, appendix 1). */

phydbl STRUCT_Mean_Rate(const t_tree *tree)
{
  return STRUCT_Mean_Rate_Data(tree->mod->smod, tree->data);
}

phydbl STRUCT_Mean_Rate_Data(const t_struct *s, const calign *data)
{
  phydbl num, den, w;
  int    site, k;

  num = den = 0.0;
  for (site = 0; site < data->n_pattern; site++)
  {
    w = 0.0;
    for (k = 0; k < s->n_comp; k++)
      w += STRUCT_Comp_Weight(s, site, k) * s->rate[k];
    num += data->wght[site] * w;
    den += data->wght[site];
  }
  return (den > 0.0) ? num / den : 1.0;
}

